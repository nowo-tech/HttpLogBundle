/**
 * HL-1 §8.1 / §8.3: the rollup tables exist only while the rollup maps them, and the documented DDL (docs/UPGRADING.md,
 * read by this test) brings a 1.15 schema to exactly the mapped one: the schema diff is empty afterwards, with the
 * default and with prefixed names, on SQLite, and on MySQL / MariaDB and PostgreSQL when HTTPLOG_TEST_MYSQL_URL /
 * HTTPLOG_TEST_PGSQL_URL point at a throwaway database.
 */
final class RollupSchemaTest extends TestCase
{
    private const PG_IDENTITY_ID = 'id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL';

    private const PG_SERIAL_ID = 'id BIGSERIAL NOT NULL';

    #[Test]
    public function withoutTheRollupTheSchemaHasNoRollupTable(): void
    {
        $sql = implode("\n", (new SchemaTool((new UsageTestDatabase(createSchema: false))->entityManager))->getCreateSchemaSql([(new UsageTestDatabase(createSchema: false))->entityManager->getClassMetadata(HttpLogEntry::class)]));

        self::assertStringNotContainsString('_daily', $sql);
        self::assertStringNotContainsString('event_seen', $sql);
    }

    #[Test]
    public function theListenerAddsBothTablesOnceAndOnlyForTheEntrysManager(): void
    {
        $db       = new UsageTestDatabase(createSchema: false, rollup: true);
        $metadata = $db->entityManager->getClassMetadata(HttpLogEntry::class);
        $sql      = implode("\n", (new SchemaTool($db->entityManager))->getCreateSchemaSql([$metadata]));
        self::assertStringContainsString('CREATE TABLE nowo_http_log_daily', $sql);
        self::assertStringContainsString('CREATE TABLE nowo_http_log_event_seen', $sql);

        $schema = new Schema();
        $schema->createTable('nowo_http_log_entry');
        $listener = new RollupSchemaListener(new RollupTables());
        $listener->postGenerateSchema(new GenerateSchemaEventArgs($db->entityManager, $schema));
        $listener->postGenerateSchema(new GenerateSchemaEventArgs($db->entityManager, $schema));
        self::assertCount(3, $schema->getTables());

        // the schema of another EntityManager (no entry table in it) gets nothing
        $empty = new Schema();
        $listener->postGenerateSchema(new GenerateSchemaEventArgs($db->entityManager, $empty));
        self::assertSame([], $empty->getTables());

        // nor does one that cannot load the entity's metadata
        $configuration = ORMSetup::createAttributeMetadataConfiguration([sys_get_temp_dir()], true);
        $configuration->setMetadataDriverImpl(new MappingDriverChain());
        if (PHP_VERSION_ID >= 80400) {
            $configuration->enableNativeLazyObjects(true);
        }
        $other = new EntityManager(DriverManager::getConnection(['driver' => 'pdo_sqlite', 'memory' => true], $configuration), $configuration, new EventManager());
        $listener->postGenerateSchema(new GenerateSchemaEventArgs($other, $empty));
        self::assertSame([], $empty->getTables());
    }

    #[Test]
    public function prefixesNameTheTablesAndTheIndexes(): void
    {
        $tables = RollupTables::fromPrefixes('app_', 'http_log_');

        self::assertSame(['app_http_log_daily', 'app_http_log_event_seen', 'app_idx_http_log_seen_day'], [$tables->daily, $tables->eventSeen, $tables->index(RollupTables::SEEN_INDEX)]);
        $schema = new Schema();
        $tables->addTo($schema);
        self::assertTrue($schema->getTable('app_http_log_daily')->hasIndex('app_uniq_http_log_daily_key'));
        self::assertTrue($schema->getTable('app_http_log_daily')->hasIndex('app_idx_http_log_daily_cred'));
    }

    /**
     * @return iterable<string, array{0: string, 1: string, 2: string}>
     */
    public static function platforms(): iterable
    {
        foreach (['sqlite' => 'sqlite', 'mysql' => 'HTTPLOG_TEST_MYSQL_URL', 'postgresql' => 'HTTPLOG_TEST_PGSQL_URL'] as $platform => $source) {
            foreach (['default' => ['', 'nowo_http_log_'], 'table_name_prefix' => ['', 'http_log_'], 'table_prefix' => ['app_', 'nowo_http_log_']] as $variant => [$tablePrefix, $tableNamePrefix]) {
                yield $platform . ' ' . $variant => [$platform, $source, $tablePrefix . '|' . $tableNamePrefix];
            }
        }
    }

    #[Test]
    #[DataProvider('platforms')]
    public function documentedDdlLeavesNoSchemaDiff(string $platform, string $source, string $prefixes): void
    {
        [$tablePrefix, $tableNamePrefix] = explode('|', $prefixes);
        $file                            = sys_get_temp_dir() . '/http-log-rollup-schema-' . bin2hex(random_bytes(6)) . '.sqlite';
        $params                          = ['driver' => 'pdo_sqlite', 'path' => $file];
        if ($platform !== 'sqlite') {
            $url = getenv($source);
            if (!is_string($url) || $url === '') {
                self::markTestSkipped($source . ' is not set.');
            }
            $params = (new DsnParser(['mysql' => 'pdo_mysql', 'postgresql' => 'pdo_pgsql', 'pgsql' => 'pdo_pgsql']))->parse($url);
            RollupTestPlatforms::dropTables($params);
        }

        // the 1.15 schema (entry with the usage columns) first, then the 1.16 rollup DDL and the 1.20.1 collation ALTERs
        $old = new UsageTestDatabase(true, $tablePrefix, $tableNamePrefix, $params, exactCollation: false);
        foreach ($this->ddl($platform, $old->rollupTables, $tablePrefix) as $statement) {
            // doctrine/dbal 3 reads a PostgreSQL identity column as a plain one: the doc says BIGSERIAL there
            $old->connection()->executeStatement($this->dbal3() ? str_replace(self::PG_IDENTITY_ID, self::PG_SERIAL_ID, $statement) : $statement);
        }
        if ($platform === 'mysql') {
            // forConnection(): doctrine/dbal 3 keeps getServerVersion() private
            $collation = ExactCollation::forConnection($old->connection());
            foreach ($this->ddl('mysql', $old->rollupTables, $tablePrefix, 'sec006-ddl', $old->table()) as $statement) {
                $old->connection()->executeStatement(str_replace(ExactCollation::MYSQL_NOPAD, (string) $collation, $statement));
            }
        }
        $old->connection()->close();

        $new  = new UsageTestDatabase(true, $tablePrefix, $tableNamePrefix, $params, false, true);
        $diff = (new SchemaTool($new->entityManager))->getUpdateSchemaSql([$new->entityManager->getClassMetadata(HttpLogEntry::class)]);
        $new->connection()->close();

        if ($platform === 'sqlite') {
            @unlink($file);
        } else {
            RollupTestPlatforms::dropTables($params);
        }

        self::assertSame([], $diff);
    }

    /**
     * doctrine/dbal 3 + PostgreSQL: a rollup table created with the identity id, then converted by the documented
     * statements run as written, leaves no schema diff. While the conversion runs, a concurrent rollup count waits
     * for the lock (here: times out) instead of failing with a NOT NULL violation (audit VB-1).
     */
    #[Test]
    public function theDbal3IdentityConversionLeavesNoSchemaDiff(): void
    {
        $params = $this->postgresql(dbal3: true);

        $old = new UsageTestDatabase(true, '', 'nowo_http_log_', $params, exactCollation: false);
        foreach ($this->ddl('postgresql', $old->rollupTables, '') as $statement) {
            $old->connection()->executeStatement($statement);
        }
        $this->insertBucket($old->connection(), '2026-11-01');

        $other = DriverManager::getConnection($params);
        $other->executeStatement("SET lock_timeout = '300ms'");
        try {
            foreach ($this->ddl('postgresql', $old->rollupTables, '', 'dbal3-rollup-id') as $statement) {
                $old->connection()->executeStatement($statement);
                if (str_starts_with($statement, 'ALTER TABLE nowo_http_log_daily ALTER id DROP IDENTITY')) {
                    $waited = null;
                    try {
                        $this->insertBucket($other, '2026-11-03');
                    } catch (DriverException $exception) {
                        $waited = $exception->getSQLState();
                    }
                    // 55P03 lock_not_available: the count waited for the ACCESS EXCLUSIVE lock, no 23502 NOT NULL
                    self::assertSame('55P03', $waited, 'the count must wait for the conversion');
                }
            }
        } finally {
            // a failed step leaves the block's transaction open: never let it block the next tests (a no-op after COMMIT)
            $old->connection()->executeStatement('ROLLBACK');
        }
        $this->insertBucket($other, '2026-11-02');
        $other->close();
        self::assertSame([1, 2], array_map(intval(...), $old->connection()->fetchFirstColumn('SELECT id FROM nowo_http_log_daily ORDER BY id')));
        $old->connection()->close();

        self::assertSame([], $this->rollupDiff($params));
        RollupTestPlatforms::dropTables($params);
    }

    /**
     * doctrine/dbal 4 + PostgreSQL: a rollup table with the DBAL 3 id (BIGSERIAL) converted by the documented
     * statements keeps counting after the highest id and leaves no schema diff (audit VB-2).
     */
    #[Test]
    public function theMoveToDbal4KeepsTheIdsAndLeavesNoSchemaDiff(): void
    {
        $params = $this->postgresql(dbal3: false);

        $old = new UsageTestDatabase(true, '', 'nowo_http_log_', $params, exactCollation: false);
        foreach ($this->ddl('postgresql', $old->rollupTables, '') as $statement) {
            $old->connection()->executeStatement(str_replace(self::PG_IDENTITY_ID, self::PG_SERIAL_ID, $statement));
        }
        $this->insertBucket($old->connection(), '2026-11-01');
        $this->insertBucket($old->connection(), '2026-11-02');
        $old->connection()->close();
        self::assertStringContainsString('ADD GENERATED BY DEFAULT AS IDENTITY', implode("\n", $this->rollupDiff($params)), 'what DBAL 4 proposes (and the doc replaces)');

        $old = new UsageTestDatabase(true, '', 'nowo_http_log_', $params, false, exactCollation: false);
        foreach ($this->ddl('postgresql', $old->rollupTables, '', 'dbal4-rollup-id') as $statement) {
            $old->connection()->executeStatement($statement);
        }
        $this->insertBucket($old->connection(), '2026-11-03');
        self::assertSame([1, 2, 3], array_map(intval(...), $old->connection()->fetchFirstColumn('SELECT id FROM nowo_http_log_daily ORDER BY id')), 'no duplicate key after the conversion');
        $old->connection()->close();

        self::assertSame([], $this->rollupDiff($params));
        RollupTestPlatforms::dropTables($params);
    }

    /**
     * @return array<string, mixed>
     */
    private function postgresql(bool $dbal3): array
    {
        $url = getenv('HTTPLOG_TEST_PGSQL_URL');
        if ($this->dbal3() !== $dbal3 || !is_string($url) || $url === '') {
            self::markTestSkipped(sprintf('doctrine/dbal %d and HTTPLOG_TEST_PGSQL_URL only.', $dbal3 ? 3 : 4));
        }
        $params = (new DsnParser(['postgresql' => 'pdo_pgsql', 'pgsql' => 'pdo_pgsql']))->parse($url);
        RollupTestPlatforms::dropTables($params);

        return $params;
    }

    /**
     * @param array<string, mixed> $params
     *
     * @return list<string>
     */
    private function rollupDiff(array $params): array
    {
        $new  = new UsageTestDatabase(true, '', 'nowo_http_log_', $params, false, true);
        $diff = (new SchemaTool($new->entityManager))->getUpdateSchemaSql([$new->entityManager->getClassMetadata(HttpLogEntry::class)]);
        $new->connection()->close();

        return $diff;
    }

    private function insertBucket(Connection $connection, string $day): void
    {
        $connection->insert('nowo_http_log_daily', ['day' => $day, 'channel' => 'outbound', 'first_seen_at' => $day . ' 10:00:00', 'last_seen_at' => $day . ' 10:00:00']);
    }

    /** doctrine/dbal 3 keeps Connection::getServerVersion() private (public since 4.0). */
    private function dbal3(): bool
    {
        return !(new ReflectionMethod(Connection::class, 'getServerVersion'))->isPublic();
    }

    /**
     * Statements of the `hl1-rollup-ddl:<platform>` block of docs/UPGRADING.md, renamed for the variant.
     *
     * @return list<string>
     */
    private function ddl(string $platform, RollupTables $tables, string $tablePrefix, string $block = 'hl1-rollup-ddl', string $entryTable = 'nowo_http_log_entry'): array
    {
        $doc = (string) file_get_contents(dirname(__DIR__, 3) . '/docs/UPGRADING.md');
        if (preg_match('/<!-- ' . $block . ':' . preg_quote($platform, '/') . ' -->\s*```sql\n(.*?)```/s', $doc, $match) !== 1) {
            throw new RuntimeException('No ' . $block . ' block for ' . $platform);
        }
        $sql = preg_replace('/^--.*$/m', '', $match[1]) ?? '';
        $sql = str_replace(['nowo_http_log_daily', 'nowo_http_log_event_seen', 'nowo_http_log_entry'], [$tables->daily, $tables->eventSeen, $entryTable], $sql);
        $sql = str_replace(['INDEX idx_http_log_', 'INDEX uniq_http_log_'], ['INDEX ' . $tablePrefix . 'idx_http_log_', 'INDEX ' . $tablePrefix . 'uniq_http_log_'], $sql);

        return array_values(array_filter(array_map(trim(...), explode(';', $sql)), static fn (string $s): bool => $s !== ''));
    }
}
